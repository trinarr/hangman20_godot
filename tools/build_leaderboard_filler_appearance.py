#!/usr/bin/env python3
"""Build migration 013 with explicit filler appearance and unchanged public IDs."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    seeds = ROOT / 'supabase/seeds'
    seed = json.loads((seeds / 'leaderboard_filler_nicknames_v4.json').read_text(encoding='utf-8'))
    previous = json.loads((seeds / 'leaderboard_filler_nicknames_v3.json').read_text(encoding='utf-8'))
    assert seed['schema_version'] == 4
    assert seed['cis_percent'] == previous['cis_percent']
    assert seed['slang_slots'] == previous['slang_slots']
    for pool in ['cis', 'us_europe']:
        assert len(seed[pool]) == 100
        for slot, row in enumerate(seed[pool], 1):
            assert row['nickname'] == previous[pool][slot-1]
            assert type(row['character_id']) is int and row['character_id'] in [1, 2]
            assert type(row['frame_id']) is int and 1 <= row['frame_id'] <= 5
            identity = f'filler:{pool}:{slot:03d}'
            number = lambda text: int(hashlib.md5(text.encode()).hexdigest()[:8], 16)
            # Preserve the appearance already assigned by migration 011.
            assert row['character_id'] == 1 + number(identity) % 2
            assert row['frame_id'] == 1 + number('frame:' + identity) % 5
    payload = json.dumps(seed, ensure_ascii=False, indent=2)
    assert '$profiles$' not in payload
    parts = ['-- Generated by tools/build_leaderboard_filler_appearance.py. Apply after 012.\nbegin;\n']
    for schema in ['leaderboard_private', 'leaderboard_dev_private']:
        parts.append(f'''alter table {schema}.fillers add column if not exists character_id integer;
alter table {schema}.fillers add column if not exists frame_id integer;
''')
    parts.append('do $seed$\ndeclare\n  profiles jsonb := $profiles$' + payload + '$profiles$::jsonb;\nbegin\n')
    for schema in ['leaderboard_private', 'leaderboard_dev_private']:
        parts.append(f'''  insert into {schema}.fillers(pool, slot, nickname, style, character_id, frame_id)
  select pool, ordinal::integer, profile->>'nickname',
    case when (profiles->'slang_slots'->pool) @> jsonb_build_array(ordinal::integer) then 'slang' else 'casual' end,
    (profile->>'character_id')::integer, (profile->>'frame_id')::integer
  from (values ('cis'), ('us_europe')) pools(pool)
  cross join lateral jsonb_array_elements(profiles->pool) with ordinality as n(profile, ordinal)
  on conflict (pool, slot) do update set nickname = excluded.nickname, style = excluded.style,
    character_id = excluded.character_id, frame_id = excluded.frame_id;
''')
    parts.append('end;\n$seed$;\n\n')
    for schema in ['leaderboard_private', 'leaderboard_dev_private']:
        parts.append(f'''alter table {schema}.fillers alter column character_id set not null;
alter table {schema}.fillers alter column frame_id set not null;
alter table {schema}.fillers drop constraint if exists fillers_character_id_check;
alter table {schema}.fillers add constraint fillers_character_id_check check (character_id between 1 and 2);
alter table {schema}.fillers drop constraint if exists fillers_frame_id_check;
alter table {schema}.fillers add constraint fillers_frame_id_check check (frame_id between 1 and 5);
''')
    previous_sql = (ROOT / 'supabase/migrations/011_player_profiles.sql').read_text(encoding='utf-8')
    for fn in ['leaderboard_sync', 'leaderboard_sync_dev']:
        start = previous_sql.index(f'create or replace function public.{fn}(')
        end = previous_sql.index('to authenticated;', start) + len('to authenticated;')
        body = previous_sql[start:end]
        old = '''    select f.*, 1 + (('x' || substr(md5(player_id),1,8))::bit(32)::bigint % 2)::integer as character_id,
      1 + (('x' || substr(md5('frame:' || player_id),1,8))::bit(32)::bigint % 5)::integer as frame_id, false as is_me, true as is_filler,'''
        assert body.count(old) == 1
        assert body.count('\n      f.nickname,\n') == 1
        body = body.replace('\n      f.nickname,\n', '\n      f.nickname, f.character_id, f.frame_id,\n')
        body = body.replace(old, '    select f.*, false as is_me, true as is_filler,')
        parts.append(body + '\n\n')
    parts.append('commit;\n')
    return ''.join(parts)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'supabase/migrations/013_leaderboard_filler_appearance.sql'
    generated = build()
    if args.check:
        assert target.read_text(encoding='utf-8') == generated, 'Regenerate 013 with tools/build_leaderboard_filler_appearance.py'
        print('200 explicit filler profiles; appearances, names, mixing and migration 013 match')
    else:
        target.write_text(generated, encoding='utf-8')
        print(target)
