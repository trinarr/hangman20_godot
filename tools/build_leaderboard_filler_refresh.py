#!/usr/bin/env python3
"""Build migration 012: refresh filler names without changing identities or mixing."""
import argparse
import json
from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parents[1]


def normalized(value):
    return unicodedata.normalize('NFKC', value).casefold().replace('ё', 'е')


def build():
    seeds = ROOT / 'supabase/seeds'
    seed = json.loads((seeds / 'leaderboard_filler_nicknames_v3.json').read_text(encoding='utf-8'))
    previous = json.loads((seeds / 'leaderboard_filler_nicknames_v2.json').read_text(encoding='utf-8'))
    assert seed['schema_version'] == 3
    assert seed['cis_percent'] == previous['cis_percent'] == {'ru': 60, 'en': 20}
    assert seed['slang_slots'] == previous['slang_slots']
    historical = set()
    for filename in ['leaderboard_filler_nicknames.json', 'leaderboard_filler_nicknames_v2.json']:
        old = json.loads((seeds / filename).read_text(encoding='utf-8'))
        historical.update(normalized(name) for pool in ['cis', 'us_europe'] for name in old[pool])
    suggestions = json.loads((ROOT / 'data/profile_nicknames.json').read_text(encoding='utf-8'))
    player_bases = [normalized(''.join(pair)) for pairs in suggestions.values() for pair in pairs]
    seen = set()
    for pool in ['cis', 'us_europe']:
        assert len(seed[pool]) == 100
        assert len(set(seed['slang_slots'][pool])) == 20
        assert all(type(slot) is int and 1 <= slot <= 100 for slot in seed['slang_slots'][pool])
        for name in seed[pool]:
            assert isinstance(name, str) and 2 <= len(name) <= 18 and not any(c.isspace() or unicodedata.category(c).startswith('C') for c in name), name
            key = normalized(name)
            assert key not in seen and key not in historical, name
            assert not any(key == base or (key.startswith(base) and key[len(base):].isdigit()) for base in player_bases), name
            seen.add(key)
    payload = json.dumps(seed, ensure_ascii=False, indent=2)
    assert '$names$' not in payload
    parts = ['-- Generated by tools/build_leaderboard_filler_refresh.py. Apply after 011.\nbegin;\n']
    parts.append('do $seed$\ndeclare\n  names jsonb := $names$' + payload + '$names$::jsonb;\nbegin\n')
    for schema in ['leaderboard_private', 'leaderboard_dev_private']:
        parts.append(f'''  insert into {schema}.fillers(pool, slot, nickname, style)
  select pool, ordinal::integer, nickname,
    case when (names->'slang_slots'->pool) @> jsonb_build_array(ordinal::integer) then 'slang' else 'casual' end
  from (values ('cis'), ('us_europe')) pools(pool)
  cross join lateral jsonb_array_elements_text(names->pool) with ordinality as n(nickname, ordinal)
  on conflict (pool, slot) do update set nickname = excluded.nickname, style = excluded.style;
''')
    parts.append('end;\n$seed$;\n\n')
    for schema in ['leaderboard_private', 'leaderboard_dev_private']:
        parts.append(f'''alter table {schema}.fillers drop constraint if exists fillers_nickname_check;
alter table {schema}.fillers add constraint fillers_nickname_check
  check (char_length(nickname) between 2 and 18 and nickname = btrim(nickname)
    and nickname !~ '[[:cntrl:][:space:]]');
''')
    parts.append('commit;\n')
    return ''.join(parts)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'supabase/migrations/012_leaderboard_filler_refresh.sql'
    generated = build()
    if args.check:
        assert target.read_text(encoding='utf-8') == generated, 'Regenerate 012 with tools/build_leaderboard_filler_refresh.py'
        print('200 unique refreshed names, lengths 2–18, unchanged identities/styles/mixing; migration 012 matches')
    else:
        target.write_text(generated, encoding='utf-8')
        print(target)
