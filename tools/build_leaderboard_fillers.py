#!/usr/bin/env python3
"""Build migration 007 from the approved server-only pool; slot order is identity."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    seed = json.loads((ROOT / 'supabase/seeds/leaderboard_filler_nicknames.json').read_text())
    assert seed.get('schema_version') == 1
    names = [name for pool in ('cis', 'us_europe') for name in seed[pool]]
    assert all(len(seed[pool]) == 100 for pool in ('cis', 'us_europe'))
    assert all(isinstance(name, str) and name == name.strip() and 2 <= len(name) <= 24 for name in names)
    assert len({name.casefold() for name in names}) == 200
    payload = json.dumps(seed, ensure_ascii=False, indent=2)
    assert '$names$' not in payload
    parts = ['-- Generated by tools/build_leaderboard_fillers.py; apply after 006.\nbegin;\n']
    for schema in ('leaderboard_private', 'leaderboard_dev_private'):
        parts.append(f'''create table if not exists {schema}.fillers (
  pool text not null check (pool in ('cis', 'us_europe')),
  slot integer not null check (slot between 1 and 100),
  nickname text not null check (char_length(nickname) between 2 and 24 and nickname = btrim(nickname)),
  primary key (pool, slot)
);
alter table {schema}.fillers enable row level security;
revoke all on {schema}.fillers from public, anon, authenticated;
''')
    parts.append('do $seed$\ndeclare\n  names jsonb := $names$' + payload + '$names$::jsonb;\nbegin\n')
    for schema in ('leaderboard_private', 'leaderboard_dev_private'):
        parts.append(f'''  insert into {schema}.fillers(pool, slot, nickname)
  select 'cis', ordinal::integer, nickname from jsonb_array_elements_text(names->'cis') with ordinality as n(nickname, ordinal)
  union all
  select 'us_europe', ordinal::integer, nickname from jsonb_array_elements_text(names->'us_europe') with ordinality as n(nickname, ordinal)
  on conflict (pool, slot) do update set nickname = excluded.nickname;
''')
    parts.append('end;\n$seed$;\n\n')
    previous = (ROOT / 'supabase/migrations/006_leaderboard_percentile.sql').read_text()
    for schema, fn in [('leaderboard_private', 'leaderboard_sync'), ('leaderboard_dev_private', 'leaderboard_sync_dev')]:
        start = previous.index(f'create or replace function public.{fn}(')
        end = previous.index('to authenticated;', start) + len('to authenticated;')
        body = previous[start:end]
        body = body.replace('p_include_top boolean default true)', "p_include_top boolean default true, p_language text default 'en')", 1)
        body = body.replace('  result jsonb;', """  result jsonb;
  board_language text := case when lower(split_part(replace(coalesce(p_language, 'en'), '_', '-'), '-', 1)) = 'ru' then 'ru' else 'en' end;
  filler_pool text := case when board_language = 'ru' then 'cis' else 'us_europe' end;""", 1)
        original = '''    from top_players
  )
  select jsonb_build_object('ok', true, 'total_players', (select total from population), 'me','''
        replacement = f'''    from top_players
  ), filler_rows as (
    select 'filler:' || f.pool || ':' || lpad(f.slot::text, 3, '0') as player_id,
      f.nickname, 0::bigint as stars, false as is_me, true as is_filler,
      (select count(*) from top_players) + row_number() over (order by f.slot) as rank
    from {schema}.fillers f where p_include_top and f.pool = filler_pool
    order by f.slot limit (select 100 - count(*) from top_players)
  ), display_top as (
    select player_id::text as player_id,
      (case when board_language = 'ru' then 'Игрок ' else 'Player ' end) || player_id::text as nickname,
      stars, is_me, false as is_filler, rank from ranked_top
    union all
    select player_id, nickname, stars, is_me, is_filler, rank from filler_rows
  )
  select jsonb_build_object('ok', true, 'language', board_language, 'total_players', (select total from population), 'me','''
        assert body.count(original) == 1
        body = body.replace(original, replacement, 1)
        body = body.replace("(select jsonb_build_object('player_id', player_id::text, 'stars', stars,", """(select jsonb_build_object('player_id', player_id::text,
      'nickname', (case when board_language = 'ru' then 'Игрок ' else 'Player ' end) || player_id::text,
      'is_filler', false, 'stars', stars,""", 1)
        body = body.replace("'player_id', player_id::text, 'stars', stars, 'rank', rank, 'is_me', is_me)", "'player_id', player_id, 'nickname', nickname, 'stars', stars, 'rank', rank, 'is_me', is_me, 'is_filler', is_filler)", 1)
        body = body.replace('from ranked_top),', 'from display_top),', 1)
        body = body.replace(f'{fn}(bigint, boolean)', f'{fn}(bigint, boolean, text)')
        parts.append(f'-- Remove the old signature to avoid ambiguous PostgREST overloads.\ndrop function if exists public.{fn}(bigint, boolean);\n' + body + '\n\n')
    parts.append('commit;\n')
    return ''.join(parts)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'supabase/migrations/007_leaderboard_fillers.sql'
    generated = build()
    if args.check:
        assert target.read_text() == generated, 'Regenerate 007 with tools/build_leaderboard_fillers.py'
        print('Approved 200-name pool and generated migration match')
    else:
        target.write_text(generated)
        print(target)
