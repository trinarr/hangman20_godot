const { PGlite } = require('@electric-sql/pglite');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const root = require('node:path').resolve(__dirname, '../..');
(async () => {
const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create schema auth;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;`);
const migration = fs.readFileSync(root+'/supabase/migrations/001_quiz_statistics.sql','utf8');
const catalog = fs.readFileSync(root+'/supabase/migrations/002_quiz_catalog.sql','utf8');
await db.exec(migration); await db.exec(catalog); await db.exec(catalog);
const keys = (await db.query('select question_key,slot from quiz_private.questions order by slot')).rows;
assert.equal(keys.length,3800); assert.equal(keys.at(-1).slot,3800);
const user='00000000-0000-0000-0000-000000000001';
await db.query('insert into auth.users values ($1)',[user]);
await db.query("select set_config('request.jwt.claim.sub',$1,false)",[user]);
await db.exec('set role authenticated');
const vote = async(key,answer)=>(await db.query('select public.quiz_answer($1,$2) as result',[key,answer])).rows[0].result.counts;
assert.deepEqual(await vote(keys[0].question_key,2),[0,0,1,0]);
assert.deepEqual(await vote(keys[0].question_key,1),[0,0,1,0]);
assert.deepEqual(await vote(keys[0].question_key,-1),[0,0,1,0]);
assert.deepEqual(await vote(keys.at(-1).question_key,3),[0,0,0,1]);
assert.deepEqual(await vote(keys[1].question_key,-2),[0,0,0,0]);
assert.deepEqual(await vote(keys[1].question_key,0),[0,0,0,0]);
await assert.rejects(()=>vote(keys[0].question_key,4));
await assert.rejects(()=>vote('unknown',0));
await assert.rejects(()=>db.query('select * from quiz_private.players'));
await assert.rejects(()=>db.query('update quiz_private.questions set counts=array[99,99,99,99]::bigint[]'));
await db.exec('reset role');
assert.equal((await db.query('select octet_length(seen) as n from quiz_private.players')).rows[0].n,475);
await db.exec('set role anon');
await assert.rejects(()=>vote(keys[0].question_key,0));
await db.exec('reset role');
await db.query("select set_config('request.jwt.claim.sub','',false)");
await db.exec('set role authenticated');
await assert.rejects(()=>vote(keys[0].question_key,0));
console.log('SQL statistics checks passed: migrations, 3800 versions, duplicate votes, read-only request, bitset growth, permissions, validation');
await db.close();

})().catch(error => { console.error(error); process.exitCode = 1; });
