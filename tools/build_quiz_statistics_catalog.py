#!/usr/bin/env python3
"""Emit append-only catalog SQL. Existing bit positions and counters never change."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def question_key(language, question):
    text = question['question'] + '\n' + '\n'.join(question['answers']) + '\n' + str(question['correct_index'])
    return f"{language}:{question['id']}:{hashlib.sha256(text.encode('utf-8')).hexdigest()}"


def build():
    keys = []
    for language in ('ru', 'en'):
        questions = json.loads((ROOT / f'data/quiz_questions_{language}.json').read_text(encoding="utf-8"))['questions']
        keys.extend(question_key(language, q) for q in questions)
    assert len(keys) == len(set(keys)), 'Duplicate catalog keys'
    values = ',\n'.join(
        "('%s',%s,decode('%s','hex'))" % tuple(key.split(':')) for key in keys
    )
    return ('-- Generated by tools/build_quiz_statistics_catalog.py. Do not truncate the table.\n'
            '-- Requires migration 016. Existing slots, votes and seen bits remain unchanged.\n'
            'insert into quiz_private.questions(language,question_id,revision_hash)\n'
            'select incoming.language,incoming.question_id,incoming.revision_hash from (values\n' + values +
            '\n) as incoming(language,question_id,revision_hash)\n'
            'where not exists (select 1 from quiz_private.questions q\n'
            '  where (q.language,q.question_id,q.revision_hash) = (incoming.language,incoming.question_id,incoming.revision_hash))\n'
            'on conflict (language,question_id,revision_hash) do nothing;\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify the generated SQL without writing')
    args = parser.parse_args()
    target = ROOT / 'supabase/quiz_statistics_catalog.sql'
    sql = build()
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != sql:
            raise SystemExit('Compact quiz catalog is stale; run tools/build_quiz_statistics_catalog.py')
    else:
        target.write_text(sql, encoding="utf-8")
    print(target)
