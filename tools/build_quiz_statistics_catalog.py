#!/usr/bin/env python3
"""Emit append-only catalog SQL. Existing bit positions and counters never change."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def question_key(language, question):
    text = question['question'] + '\n' + '\n'.join(question['answers']) + '\n' + str(question['correct_index'])
    return f"{language}:{question['id']}:{hashlib.sha256(text.encode('utf-8')).hexdigest()}"


def build():
    keys = []
    for language in ('ru', 'en'):
        questions = json.loads((ROOT / f'data/quiz_questions_{language}.json').read_text(encoding="utf-8"))['questions']
        keys.extend(question_key(language, q) for q in questions)
    assert len(keys) == len(set(keys)), 'Duplicate catalog keys'
    values = ',\n'.join("('%s')" % key for key in keys)
    return ('-- Generated by tools/build_quiz_statistics_catalog.py. Do not truncate the table.\n'
            'insert into quiz_private.questions(question_key)\nselect incoming.question_key from (values\n' + values +
            '\n) as incoming(question_key)\nwhere not exists (select 1 from quiz_private.questions q where q.question_key = incoming.question_key)\non conflict (question_key) do nothing;\n')


if __name__ == '__main__':
    target = ROOT / 'supabase/migrations/002_quiz_catalog.sql'
    target.write_text(build(), encoding="utf-8")
    print(target)
