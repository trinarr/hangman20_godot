#!/usr/bin/env python3
"""Build migration 008 without rewriting the deployed 007 seed or selection."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]


def build():
    seed = json.loads((ROOT / 'supabase/seeds/leaderboard_filler_nicknames_v2.json').read_text())
    assert seed['schema_version'] == 2
    assert seed['cis_percent'] == {'ru':60, 'en':20}
    previous_seed = json.loads((ROOT / "supabase/seeds/leaderboard_filler_nicknames.json").read_text())
    names = []
    for pool in ['cis','us_europe']:
        assert len(seed[pool]) == 100
        assert len(set(seed['slang_slots'][pool])) == 20
        assert all(isinstance(slot,int) and 1 <= slot <= 100 for slot in seed['slang_slots'][pool])
        assert sum(new != old for new,old in zip(seed[pool],previous_seed[pool])) == 20
        assert all(seed[pool][slot-1] != previous_seed[pool][slot-1] for slot in seed['slang_slots'][pool])
        names.extend(seed[pool])
    assert all(isinstance(name,str) and name == name.strip() and 2 <= len(name) <= 24 for name in names)
    assert len({name.casefold() for name in names}) == 200
    payload = json.dumps(seed,ensure_ascii=False,indent=2)
    assert '$names$' not in payload
    parts=['-- Generated by tools/build_leaderboard_filler_mix.py. Apply after 007.\nbegin;\n']
    for schema in ['leaderboard_private','leaderboard_dev_private']:
        parts.append(f"alter table {schema}.fillers add column if not exists style text not null default 'casual' check (style in ('casual', 'slang'));\n")
    parts.append('do $seed$\ndeclare\n  names jsonb := $names$'+payload+'$names$::jsonb;\nbegin\n')
    for schema in ['leaderboard_private','leaderboard_dev_private']:
        parts.append(f'''  insert into {schema}.fillers(pool, slot, nickname, style)
  select pool, ordinal::integer, nickname,
    case when (names->'slang_slots'->pool) @> jsonb_build_array(ordinal::integer) then 'slang' else 'casual' end
  from (values ('cis'),('us_europe')) pools(pool)
  cross join lateral jsonb_array_elements_text(names->pool) with ordinality as n(nickname, ordinal)
  on conflict (pool, slot) do update set nickname=excluded.nickname, style=excluded.style;
''')
    parts.append('end;\n$seed$;\n\n')
    previous=(ROOT/'supabase/migrations/007_leaderboard_fillers.sql').read_text()
    for schema,fn in [('leaderboard_private','leaderboard_sync'),('leaderboard_dev_private','leaderboard_sync_dev')]:
        start=previous.index(f'create or replace function public.{fn}(')
        end=previous.index('to authenticated;',start)+len('to authenticated;')
        body=previous[start:end]
        original="  filler_pool text := case when board_language = 'ru' then 'cis' else 'us_europe' end;"
        assert body.count(original)==1
        body=body.replace(original,f"  cis_percentage integer := case when board_language = 'ru' then {seed['cis_percent']['ru']} else {seed['cis_percent']['en']} end;",1)
        start=body.index('  ), filler_rows as (')
        end=body.index('  ), display_top as (',start)
        replacement=f'''  ), filler_quotas as (
    select 100-count(*) as missing, ((100-count(*))*cis_percentage+50)/100 as cis_count from top_players
  ), scored_fillers as (
    -- Stable pseudorandom sampling for one account, independent of JWT rotation.
    select f.*, row_number() over (partition by f.pool
      order by md5('pick:v2:' || player::text || ':' || f.pool || ':' || f.slot::text), f.slot) as pool_rank,
      md5('order:v2:' || player::text || ':' || f.pool || ':' || f.slot::text) as display_order
    from {schema}.fillers f where p_include_top
  ), chosen_fillers as (
    select f.* from scored_fillers f cross join filler_quotas q
    where f.pool_rank <= case when f.pool='cis' then q.cis_count else q.missing-q.cis_count end
  ), filler_rows as (
    select 'filler:' || f.pool || ':' || lpad(f.slot::text, 3, '0') as player_id,
      f.nickname, 0::bigint as stars, false as is_me, true as is_filler,
      (select count(*) from top_players) + row_number() over (order by f.display_order, f.pool, f.slot) as rank
    from chosen_fillers f
'''
        body=body[:start]+replacement+body[end:]
        parts.append(body+'\n\n')
    parts.append('commit;\n')
    return ''.join(parts)


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    target=ROOT/'supabase/migrations/008_leaderboard_filler_mix.sql'
    generated=build()
    if args.check:
        assert target.read_text()==generated, 'Regenerate 008 with tools/build_leaderboard_filler_mix.py'
        print('200 names, 20 slang per pool, percentage rules and migration 008 match')
    else:
        target.write_text(generated)
        print(target)
